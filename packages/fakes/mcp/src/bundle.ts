import fs from "node:fs";
import path from "node:path";
import { build } from "esbuild";

/** Where a Recipe's fakes index and scenarios index are, and where the bundle goes. */
export interface BundleOptions {
  /** The module exporting `fakes`; `mcp/index.ts`. */
  fakes?: string;
  /** The module exporting `world`; `scenarios/index.ts`. */
  scenarios?: string;
}

const PNPM_STORE = "node_modules/.pnpm/";

export const BUNDLE_DEFAULTS = {
  fakes: "mcp/index.ts",
  scenarios: "scenarios/index.ts",
  out: "dist/sidecar.js",
};

// The relative import of `file` from `base`, as an ES module specifier.
function specifier(base: string, file: string) {
  const relative = path.relative(base, file).split(path.sep).join("/");
  return relative.startsWith(".") ? relative : `./${relative}`;
}

/**
 * The Harbor sidecar as one file: the package's built-in entrypoint over the Recipe's fakes and
 * world, with the host, every fake and their dependencies. A plane builds the sidecar's image
 * with no route to a package registry, so the image installs nothing and runs this file.
 *
 * Paths are resolved from the working directory, and the output names them relative to the
 * directory holding both indexes, so it does not depend on where the command runs.
 */
export async function bundle(options: BundleOptions = {}): Promise<string> {
  // Real paths, as esbuild names every module by, or the entry is named from outside a linked
  // directory such as macOS's /var.
  const fakes = fs.realpathSync(path.resolve(options.fakes ?? BUNDLE_DEFAULTS.fakes));
  const scenarios = fs.realpathSync(path.resolve(options.scenarios ?? BUNDLE_DEFAULTS.scenarios));
  let base = path.dirname(fakes);
  while (path.relative(base, scenarios).startsWith("..")) base = path.dirname(base);
  const from = [specifier(base, fakes), specifier(base, scenarios)];
  // The package is imported by name, so the entry and the fakes share the copy the fakes resolve.
  const entry = [
    `import { serveSidecar } from "@introspection-ai/mcp-fakes";`,
    `import { fakes } from ${JSON.stringify(from[0])};`,
    `import { world } from ${JSON.stringify(from[1])};`,
    `await serveSidecar(fakes, world);`,
  ].join("\n");
  const result = await build({
    absWorkingDir: base,
    stdin: { contents: entry, resolveDir: base, sourcefile: "mcp-fakes-sidecar.js", loader: "js" },
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    banner: {
      js: `// Generated by mcp-fakes bundle from ${from.join(" and ")}. Do not edit.`,
    },
    // Unminified, esbuild names each module by where the package manager installed it, in a
    // comment and as a CommonJS module's key (`node_modules/.pnpm/ms@2.1.3/…` under pnpm), so the
    // bundle would differ by install. keepNames keeps a stack trace's function names.
    minify: true,
    keepNames: true,
    write: false,
    logLevel: "error",
  });
  const source = result.outputFiles[0].text;
  const directories = [base, fs.realpathSync(process.cwd())].filter(
    (directory) => directory !== path.parse(directory).root,
  );
  const leaked = [PNPM_STORE, ...directories].find((part) => source.includes(part));
  if (leaked)
    throw new Error(
      `The bundle names ${leaked}, so it would depend on where or how the fakes were installed`,
    );
  return source;
}

/** Whether `out` holds exactly what the sources bundle to now. */
export async function isCurrent(out: string, options: BundleOptions = {}): Promise<boolean> {
  const source = await bundle(options);
  return fs.existsSync(out) && fs.readFileSync(out, "utf8") === source;
}

export async function writeBundle(out: string, options: BundleOptions = {}): Promise<void> {
  const source = await bundle(options);
  fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
  fs.writeFileSync(out, source);
}
