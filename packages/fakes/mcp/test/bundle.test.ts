import { execFile, spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { expect, test } from "vitest";
import { bundle } from "../src/bundle.js";
import { SIDECAR_PORT } from "../src/index.js";
import { callTool } from "./client.js";

const run = promisify(execFile);
const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CLI = path.join(ROOT, "dist", "cli.js");
const FAKES = path.join(ROOT, "test", "fixtures", "fakes");

// The command as the package ships it, run in the fixture Recipe's fakes/.
async function cli(...args: string[]) {
  try {
    const { stdout, stderr } = await run(process.execPath, [CLI, ...args], { cwd: FAKES });
    return { code: 0, stdout, stderr };
  } catch (error) {
    const failed = error as { code: number; stdout: string; stderr: string };
    return { code: failed.code, stdout: failed.stdout, stderr: failed.stderr };
  }
}

const scratch = (prefix: string) => fs.mkdtempSync(path.join(os.tmpdir(), prefix));

// Starts a bundle from a directory holding nothing else, and resolves with its port.
function sidecar(file: string, env: Record<string, string>) {
  const dir = scratch("mcp-fakes-sidecar-");
  fs.copyFileSync(file, path.join(dir, "sidecar.js"));
  const child = spawn(process.execPath, ["sidecar.js"], {
    cwd: dir,
    env: { PATH: process.env.PATH, ...env },
    stdio: ["ignore", "pipe", "inherit"],
  });
  const port = new Promise<number>((resolve, reject) => {
    child.stdout.on("data", (chunk: Buffer) => {
      const match = String(chunk).match(/ready on port (\d+)/);
      if (match) resolve(Number(match[1]));
    });
    child.once("exit", (code) => reject(new Error(`the sidecar exited with ${code}`)));
  });
  return { child, port };
}

test(
  "bundle writes one file, and --check fails once it is stale",
  { timeout: 60_000 },
  async () => {
    const out = path.join(scratch("mcp-fakes-bundle-"), "dist", "sidecar.js");
    expect((await cli("bundle", "--out", out, "--check")).code).toBe(1);
    expect(await cli("bundle", "--out", out)).toEqual({ code: 0, stdout: "", stderr: "" });
    const source = fs.readFileSync(out, "utf8");
    expect(source.split("\n")[0]).toBe(
      "// Generated by mcp-fakes bundle from ./mcp/index.ts and ./scenarios/index.ts. Do not edit.",
    );
    expect(source).not.toContain(ROOT);
    expect((await cli("bundle", "--out", out, "--check")).code).toBe(0);
    fs.appendFileSync(out, "// edited\n");
    const stale = await cli("bundle", "--out", out, "--check");
    expect(stale.code).toBe(1);
    expect(stale.stderr).toContain(`${out} is stale: run mcp-fakes bundle --out ${out}`);
  },
);

test("the sidecar runs with nothing installed beside it", { timeout: 60_000 }, async () => {
  const out = path.join(scratch("mcp-fakes-bundle-"), "sidecar.js");
  expect((await cli("bundle", "--out", out)).code).toBe(0);
  const manifests = path.join(scratch("mcp-fakes-verifier-"), "verifier");
  const { child, port } = sidecar(out, {
    MCP_FAKES_PORT: "0",
    MCP_FAKES_SCENARIO: "broken",
    MCP_FAKES_MANIFEST_DIR: manifests,
  });
  try {
    const url = `http://127.0.0.1:${await port}`;
    const sent = await callTool(`${url}/mail/mcp`, "send-email", {
      to: ["a@example.test"],
      subject: "Hi",
    });
    expect(sent).toEqual({ text: "Sent email-1", isError: false, structuredContent: undefined });
    expect((await (await fetch(`${url}/mail/admin/state`)).json()).emails).toHaveLength(1);
    expect((await (await fetch(`${url}/notes/admin/initial-state`)).json()).brokenId).toBe(
      "note-1",
    );
    const written = JSON.parse(
      fs.readFileSync(path.join(manifests, "mcp", "notes", "manifest.json"), "utf8"),
    );
    expect(written.server).toEqual({ name: "notes", version: "1.2.3" });
  } finally {
    child.kill("SIGTERM");
  }
});

test(
  "the sidecar listens on the sidecar port unless told otherwise",
  { timeout: 60_000 },
  async () => {
    expect(SIDECAR_PORT).toBe(7353);
    const out = path.join(scratch("mcp-fakes-bundle-"), "sidecar.js");
    expect((await cli("bundle", "--out", out)).code).toBe(0);
    const { child, port } = sidecar(out, {});
    try {
      expect(await port).toBe(SIDECAR_PORT);
      const health = await fetch(`http://127.0.0.1:${SIDECAR_PORT}/health`);
      expect(await health.json()).toEqual({ ok: true });
    } finally {
      child.kill("SIGTERM");
    }
  },
);

// A Recipe's fakes/ whose packages, an ES module and a CommonJS one, are installed flat, as npm
// does, or each under node_modules/.pnpm/<name>@<version>/ and linked from node_modules/, as pnpm
// does.
function installed(
  layout: "npm" | "pnpm",
  world = (_dir: string) => "export const world = () => ({});\n",
) {
  const dir = fs.realpathSync(scratch(`mcp-fakes-${layout}-`));
  const write = (file: string, text: string) => {
    fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    fs.writeFileSync(path.join(dir, file), text);
  };
  const packages: Record<string, { type?: string; source: string }> = {
    "@introspection-ai/mcp-fakes": {
      type: "module",
      source: "export async function serveSidecar(fakes, world) { return [fakes, world]; }",
    },
    greeting: { type: "module", source: 'export const greeting = "hello";' },
    farewell: { source: 'module.exports = { farewell: "goodbye" };' },
  };
  for (const [name, { type, source }] of Object.entries(packages)) {
    const manifest = JSON.stringify({ name, version: "1.0.0", type, main: "index.js" });
    const at =
      layout === "npm"
        ? `node_modules/${name}`
        : `node_modules/.pnpm/${name.replace("/", "+")}@1.0.0/node_modules/${name}`;
    write(`${at}/package.json`, manifest);
    write(`${at}/index.js`, source);
    if (layout === "pnpm") {
      fs.mkdirSync(path.dirname(path.join(dir, "node_modules", name)), { recursive: true });
      fs.symlinkSync(path.join(dir, at), path.join(dir, "node_modules", name), "dir");
    }
  }
  write(
    "mcp/index.ts",
    'import { greeting } from "greeting";\nimport legacy from "farewell";\nexport const fakes = { greeting, farewell: legacy.farewell };\n',
  );
  write("scenarios/index.ts", world(dir));
  const sources = {
    fakes: path.join(dir, "mcp/index.ts"),
    scenarios: path.join(dir, "scenarios/index.ts"),
  };
  return { dir, sources };
}

test("the bundle is the same whichever package manager installed the fakes' packages", async () => {
  const npm = await bundle(installed("npm").sources);
  expect(npm).toContain('"goodbye"');
  expect(npm).not.toContain("node_modules");
  expect(await bundle(installed("pnpm").sources)).toBe(npm);
});

test("the bundler refuses a bundle that names the install or the fakes' directory", async () => {
  const store = installed("npm", () => 'export const world = () => ({ at: "node_modules/.pnpm/x" });\n');
  await expect(bundle(store.sources)).rejects.toThrow(
    "The bundle names node_modules/.pnpm/, so it would depend on where or how the fakes were installed",
  );
  const here = installed("npm", (dir) => `export const world = () => ({ at: ${JSON.stringify(dir)} });\n`);
  await expect(bundle(here.sources)).rejects.toThrow(`The bundle names ${here.dir}`);
});

test("the bundler refuses an unknown command", async () => {
  const usage = await cli("pack");
  expect(usage.code).toBe(2);
  expect(usage.stderr).toContain("Usage: mcp-fakes bundle [--fakes <file>]");
});
